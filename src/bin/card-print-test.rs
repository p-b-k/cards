use seahaven::cards::{Card, NUM_RANKS, NUM_SUITS};

pub fn main() {
    for s in 0..NUM_SUITS {
        for r in 0..NUM_RANKS {
            let c = Card::from_index(NUM_RANKS * s + r).unwrap();
            print!("{c} ");
        }
        println!();
    }
}
